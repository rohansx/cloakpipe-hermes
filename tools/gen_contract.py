"""Write a contract that covers every Hermes tool from the schema snapshot.

    python3 tools/gen_contract.py contracts/hermes-tools.json contracts/hermes-all

writes ``contracts/hermes-all.manifest.yaml`` and ``contracts/hermes-all.cedar``. Each tool's
arguments come from its schema (closed: anything else is undeclared_argument); the rules that
need judgment (side effects, approvals, deny patterns) are copied from the curated
``contracts/hermes.manifest.yaml`` and ``contracts/hermes.cedar`` for the tools they cover,
and the Cedar file gets a plain permit for every other tool. Standard library only.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
CURATED_MANIFEST = HERE / "contracts" / "hermes.manifest.yaml"
CURATED_CEDAR = HERE / "contracts" / "hermes.cedar"
MAX_DEPTH = 3


def constraint(schema: dict, depth: int = 0) -> dict | None:
    """One manifest argument constraint from one JSON-schema property, or None to skip it."""
    t = schema.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), None)
    if t is None and schema.get("anyOf"):
        types = [a.get("type") for a in schema["anyOf"] if isinstance(a, dict)]
        t = next((x for x in types if x in ("string", "integer", "number", "boolean")), None)
    out: dict = {}
    if t in ("string", "integer", "number", "boolean", "array", "object"):
        out["type"] = t
    if "enum" in schema and isinstance(schema["enum"], list) and schema["enum"]:
        out["enum"] = schema["enum"]
    if "const" in schema:
        out["const"] = schema["const"]
    if t in ("integer", "number"):
        if "minimum" in schema:
            out["min"] = schema["minimum"]
        if "maximum" in schema:
            out["max"] = schema["maximum"]
    if t in ("string", "array"):
        lo, hi = ("minLength", "maxLength") if t == "string" else ("minItems", "maxItems")
        if lo in schema:
            out["min_len"] = schema[lo]
        if hi in schema:
            out["max_len"] = schema[hi]
    if t == "array" and isinstance(schema.get("items"), dict) and depth < MAX_DEPTH:
        item = constraint(schema["items"], depth + 1)
        if item:
            out["items"] = item
    if t == "object" and isinstance(schema.get("properties"), dict) and depth < MAX_DEPTH:
        props = {}
        required = set(schema.get("required") or [])
        for name, sub in schema["properties"].items():
            c = constraint(sub, depth + 1)
            if c:
                if name in required:
                    c["required"] = True
                props[name] = c
        if props:
            out["properties"] = props
    return out or None


def curated_tools(text: str) -> dict[str, str]:
    """tool name -> its block in the curated manifest (verbatim), by indentation."""
    blocks: dict[str, str] = {}
    current = None
    lines: list[str] = []
    in_tools = False
    for line in text.splitlines():
        if line.startswith("tools:"):
            in_tools = True
            continue
        if not in_tools:
            continue
        m = re.match(r"^  (\w+):\s*$", line)
        if m:
            if current:
                blocks[current] = "\n".join(lines)
            current, lines = m.group(1), [line]
        elif current is not None:
            lines.append(line)
    if current:
        blocks[current] = "\n".join(lines)
    return blocks


def main(snapshot: Path, out_stem: Path) -> None:
    data = json.loads(snapshot.read_text())
    tools = data["tools"]
    curated = curated_tools(CURATED_MANIFEST.read_text())
    cedar = CURATED_CEDAR.read_text()
    permitted = set(re.findall(r'permit \(principal == Release::"hermes", action == Action::"(\w+)"', cedar))

    out = ["# Generated by tools/gen_contract.py from contracts/hermes-tools.json: every Hermes",
           "# built-in tool, arguments closed to its schema. Tools with hand-written rules",
           "# (side effects, approvals) are copied from contracts/hermes.manifest.yaml.",
           "release: hermes", 'version: "0.1-all"', f"policy: {out_stem.name}.cedar", "tools:"]
    permits = []
    for name in sorted(tools):
        if name in curated:
            out.append(curated[name])
        else:
            params = tools[name].get("parameters") or {}
            required = set(params.get("required") or [])
            args = {}
            for arg, schema in (params.get("properties") or {}).items():
                c = constraint(schema if isinstance(schema, dict) else {})
                if c:
                    if arg in required:
                        c["required"] = True
                    args[arg] = c
            out.append(f"  {name}:" if args else f"  {name}: {{}}")
            if args:
                out.append("    args:")
                for arg, c in args.items():
                    out.append(f"      {arg}: {json.dumps(c)}")
        if name not in permitted:
            permits.append(f'@id("{name}")\npermit (principal == Release::"hermes", action == Action::"{name}", resource);')
    Path(f"{out_stem}.manifest.yaml").write_text("\n".join(out) + "\n")
    Path(f"{out_stem}.cedar").write_text(
        "// Generated by tools/gen_contract.py: the curated policy, then a permit per remaining tool.\n\n"
        + cedar.rstrip() + "\n\n" + "\n\n".join(permits) + "\n")
    print(f"{len(tools)} tools -> {out_stem}.manifest.yaml ({len(curated)} curated), {len(permits)} generated permits")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), Path(sys.argv[2]))
